#!/usr/bin/env python3
"""Generates the REA/Ghidra seed file (REA_GHIDRA_SEED_FILE) for the main code.

Ghidra only follows direct calls; handlers reached through jump tables are left
without analysis and without cross-references. This script reads those tables
from the binary itself and emits `function` entries, plus the names from
analysis/main_8000.sym as `label`/`function`.

Format (REA): 0x<address>\t<function|code|label>[\t<name>]

usage: ghidra_seeds.py build/extracted/boot/main_8000.bin analysis/main_8000.sym analysis/ghidra_seeds.tsv
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

BASE = 0x8000
FIXED = {  # entries confirmed in the code (see docs/AMIGA_ANALYSIS.md)
    0x8000: "start", 0x80C2: None, 0xAB08: "draw_bob",
    0x1015E: "irq_l6_exter", 0x1015C: "irq_l4_audio", 0x10266: "irq_l3_vbl", 0x101DC: "irq_l2_ports",
    0x101CC: "irq_l1",
}
# JMP/JSR table(PC,Dn): the BRA table starts at the base address itself
PC_TABLES = {0x86FA: "level_load", 0x8B92: None, 0x91B0: "level_tick", 0xAECA: "effect",
             0xC912: None, 0xDBDA: None, 0xDD50: None, 0xF10A: None, 0xFBE0: None, 0x11746: None}
OBJ_DESC = 0xBEB0  # object type descriptors, 16 bytes
ACT_BASE, ACT_TABLE = 0x9EC4, 0x9D96  # activation: ACT_BASE + word(ACT_TABLE + type)
OBJ_LISTS = (0xA562, 0xA828, 0xAA3A)  # object lists of levels 0..2 (12 bytes per entry)


class Image:
    def __init__(self, data: bytes):
        self.data = data
        self.end = BASE + len(data)

    def sw(self, a: int) -> int:
        return struct.unpack_from(">h", self.data, a - BASE)[0]

    def uw(self, a: int) -> int:
        return struct.unpack_from(">H", self.data, a - BASE)[0]

    def code(self, a: int) -> bool:
        return BASE <= a < self.end and a % 2 == 0


def bra_chain(img: Image, start: int, limit: int = 64) -> list[int]:
    """Targets of a BRA.S/BRA.W sequence (stops at the first item that is not a BRA)."""
    out, a = [], start
    while len(out) < limit and img.code(a):
        w = img.uw(a)
        if w & 0xFF00 != 0x6000:
            break
        if w & 0xFF == 0:
            t, a = a + 2 + img.sw(a + 2), a + 4
        else:
            disp = w & 0xFF
            t, a = a + 2 + (disp - 256 if disp & 0x80 else disp), a + 2
        if img.code(t):
            out.append(t)
    return out


def object_types(img: Image) -> list[tuple[int, int, int]]:
    out = []
    for t in range(1, 256):
        d = OBJ_DESC + 16 * t
        if d + 4 > img.end:
            break
        h, death = d + img.sw(d), d + 2 + img.sw(d + 2)
        if not (img.code(h) and img.code(death)):
            break
        out.append((t, h, death))
    return out


def activation_handlers(img: Image) -> dict[int, int]:
    types = set()
    for lst in OBJ_LISTS:
        a = lst
        while img.code(a) and img.sw(a) >= 0:
            types.add(img.uw(a))
            a += 12
    out = {}
    for t in sorted(types):
        if img.code(ACT_TABLE + t):
            off = img.sw(ACT_TABLE + t)
            if off and img.code(ACT_BASE + off):
                out[t] = ACT_BASE + off
    return out


def read_sym(path: Path) -> dict[int, str]:
    names = {}
    for line in path.read_text().splitlines():
        s = line.strip()
        if not s or s.startswith(("#", "+")):
            continue
        parts = s.split(None, 2)
        if len(parts) >= 2:
            names[int(parts[0], 16)] = parts[1]
    return names


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    img = Image(Path(argv[1]).read_bytes())
    names = read_sym(Path(argv[2]))
    funcs: dict[int, str | None] = dict(FIXED)
    for base, prefix in PC_TABLES.items():
        for i, t in enumerate(bra_chain(img, base)):
            funcs.setdefault(t, f"{prefix}_{i}" if prefix else None)
    for t, h, death in object_types(img):
        funcs.setdefault(h, f"obj{t:02d}_update")
        funcs.setdefault(death, None)
    for t, h in activation_handlers(img).items():
        funcs.setdefault(h, f"obj_activate_{t:02x}")
    for a, n in names.items():
        if a in funcs:
            funcs[a] = n
    lines = ["# Generated by tools/ghidra_seeds.py - do not edit by hand; edit analysis/main_8000.sym or the script."]
    used = set()
    for a in sorted(funcs):
        n = funcs[a]
        if n and n not in used:
            used.add(n)
            lines.append(f"0x{a:x}\tfunction\t{n}")
        else:
            lines.append(f"0x{a:x}\tfunction")
    for a in sorted(names):
        if a not in funcs and names[a] not in used:
            used.add(names[a])
            lines.append(f"0x{a:x}\tlabel\t{names[a]}")
    Path(argv[3]).write_text("\n".join(lines) + "\n")
    print(f"{argv[3]}: {len(funcs)} functions, {len(lines) - 1 - len(funcs)} labels")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
