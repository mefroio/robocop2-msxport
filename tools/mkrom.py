#!/usr/bin/env python3
"""Builds the prototype MegaROM (Konami SCC style mapper, MegaRAM compatible).

8 KiB banks:
  0-1   code (msx/rc2.asm, org 4000h, padded up to 8000h)
  2-3   game logic modules (msx/rc2.asm org 8000h: objects.asm, mapobj.asm; one at a time at 8000h
        during the game's tick)
  4     game logic of the level (org A000h: mapped at A000h during the tick)
  5-12  level tiles: VRAM 10000h-1FFFFh (pages 2-3) generated by tools/msxconv.py
  10..  map: 25 rows of 320 bytes per bank (no row crosses a bank boundary)
  then  RoboCop sprite data (tools/msxsprites.py), from bank SPR_BASE_BANK
  then  run-time HUD data (tools/msxhudrt.py, 2 banks), from bank HUD_BANK
  then  the map attributes (tools/msxconv.py .atrp: packed, copied to page-0 RAM), bank ATR_BANK
  then  the static HUD image (tools/msxhud.py), bank HUD_IMG_BANK
  then  the level's tables, bank LEVEL_BANK: tile per DATAL tile offset (.otile, OTILE = 8000h)
Generates build/msx/gen/banks.inc, rowtab.inc, options.inc (build options, see OPTIONS),
input.inc (the JOY script) and the original's tables the logic banks include (tools/amitab.py
with analysis/amiga_tables.tsv, from the level's RAM image build/ram/level1_full.bin), copies the level palette, the HUD (tools/msxhud.py) and RoboCop's
logic tables (tools/player.py --inc) into build/msx/gen, assembles with z80asm and writes
build/msx/rc2.rom.

The view: the MSX shows 256 x 163 of the game's 288 x 176 camera; banks.inc gets the factors of
msx/player.asm's mapping (VIEW_KX, VIEW_KY: the extra MSX camera range over the game's, 16.16).

usage: mkrom.py build/msx/level1 build/msx/rc2.rom [NAME=VALUE ...] [JOY=F:C:KEYS,...]
       (e.g. DEMO_ACTORS=2 for a test ROM with two demo enemies; JOY=70:40:r,120:5:ru plays
       the joystick script of tools/amigaemu.py game --joy instead of reading the controls:
       keys u d l r f pressed for C game frames from game frame F)
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BANK = 0x2000
LOGIC = ("LC1", "LC2", "L1")        # logic banks after the two code banks (msx/rc2.asm sections):
                                    # modules at 8000h (one at a time), the level at A000h
ROWS_PER_BANK = 25
COLS = 160
VIEW_LINES = 163                    # msx/msx.inc
OPTIONS = {
    "FORCE_V9938": (0, "1 = use the MSX2 scroll engine even on a V9958 (test)"),
    "DEMO_ACTORS": (0, "demo: objects besides RoboCop (0-5, msx/sprites.asm demo_actors)"),
    "DEMO_HUD": (0, "1 = the HUD demo drives the panel instead of the game's values"),
}
KEY_BITS = {"u": 0x01, "d": 0x02, "l": 0x04, "r": 0x08, "f": 0x10}   # the joystick byte ($802E)


def input_inc(script: str) -> str:
    """input.inc: the JOY script as [start, count, bits] entries (msx/player.asm joy_read)."""
    lines = ["; generated by tools/mkrom.py: joystick script (JOY=...; INPUT_SCRIPT in options.inc)",
             "input_script:"]
    for item in filter(None, script.split(",")):
        start, count, keys = item.split(":")
        bits = 0
        for k in keys:
            bits |= KEY_BITS[k]
        lines.append(f"        dw {int(start)}, {int(count)}\n        db 0x{bits:02X}")
    lines.append("        dw 0xFFFF")
    return "\n".join(lines) + "\n"


def bob_hash(sprites_json: Path) -> bytes:
    """The level's BOB frames (tools/msxsprites.py) by the game's (A2, D4): 256 slots of 8 bytes
    [A2 (3, low first), D4 (2), frame id, 0, 0], open addressing from hash h = the XOR of those 5
    bytes (msx/bob.asm bob_frame); an empty slot has id FFh."""
    frames = json.loads(sprites_json.read_text()).get("bobs", [])
    if len(frames) > 220:
        raise SystemExit(f"{len(frames)} BOB frames: too many for the 256-slot table")
    table = bytearray(b"\x00\x00\x00\x00\x00\xff\x00\x00" * 256)
    for f in frames:
        a2, d4 = f["addr"], (f["h"] << 6) | (f["w"] // 16 + 1)
        key = bytes([a2 & 0xFF, (a2 >> 8) & 0xFF, (a2 >> 16) & 0xFF, d4 & 0xFF, d4 >> 8])
        h = key[0] ^ key[1] ^ key[2] ^ key[3] ^ key[4]
        while table[8 * h + 5] != 0xFF:
            h = (h + 1) & 255
        table[8 * h:8 * h + 8] = key + bytes([f["id"], 0, 0])
    return bytes(table)


def equates(path: Path) -> dict[str, int]:
    out = {}
    for line in path.read_text().splitlines():
        if ": equ " in line:
            k, v = line.split(": equ ")
            out[k.strip()] = int(v.split()[0], 0)
    return out


def main(argv: list[str]) -> int:
    if len(argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    level, out = Path(argv[1]).resolve(), Path(argv[2]).resolve()
    opts = {k: v for k, (v, _) in OPTIONS.items()}
    script = ""
    for a in argv[3:]:
        k, _, v = a.partition("=")
        if k == "JOY":
            script = v
            continue
        if k not in OPTIONS or not v:
            print(f"unknown option {a!r}; known: {', '.join(OPTIONS)}, JOY", file=sys.stderr)
            return 2
        opts[k] = int(v, 0)
    vram = level.with_suffix(".vram").read_bytes()
    mp = level.with_suffix(".map").read_bytes()
    rows = len(mp) // (COLS * 2)
    gen = out.parent / "gen"
    gen.mkdir(parents=True, exist_ok=True)
    shutil.copy(level.with_suffix(".pal"), gen / "level1.pal")
    for name in ("hud.pal", "robocop.inc", "hud_rt.inc", "player.inc"):
        shutil.copy(level.parent / name, gen / name)
    atr = level.with_suffix(".atrp").read_bytes()               # (packed: copied to page-0 RAM)
    otile = level.with_suffix(".otile").read_bytes()
    otile += level.with_suffix(".atr2").read_bytes()        # (ATR2 = OTILE + 400h)
    otile += b"\xff" * (0x540 - len(otile)) + bob_hash(level.parent / "robocop.json")   # (BOBHASH = 8540h)
    hud_img = (level.parent / "hud.sc5").read_bytes()
    if len(atr) > BANK or len(hud_img) > BANK:
        print("error: the map attributes or the HUD image do not fit a bank", file=sys.stderr)
        return 1
    sprites = (level.parent / "robocop.bin").read_bytes()
    hudrt = (level.parent / "hud_rt.bin").read_bytes()
    if len(hudrt) > 2 * BANK:
        print("error: hud_rt.bin is larger than two banks", file=sys.stderr)
        return 1

    r = subprocess.run([sys.executable, "-I", str(ROOT / "tools" / "amitab.py"),
                        str(ROOT / "build" / "ram" / "level1_full.bin"), str(ROOT / "analysis" / "amiga_tables.tsv"),
                        str(gen)], capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout + r.stderr, file=sys.stderr)
        return 1
    bank_tiles = 2 + len(LOGIC)
    tiles = vram[0x10000:0x20000]
    bank_map = bank_tiles + len(tiles) // BANK
    map_banks = []
    rowtab = []
    for b in range(0, rows, ROWS_PER_BANK):
        chunk = mp[b * COLS * 2:(b + ROWS_PER_BANK) * COLS * 2]
        map_banks.append(chunk + b"\xff" * (BANK - len(chunk)))
    for r in range(rows):
        rowtab.append(f"        db {bank_map + r // ROWS_PER_BANK}\n        dw 0x{0xA000 + (r % ROWS_PER_BANK) * COLS * 2:04X}\n")
    bank_spr = bank_map + len(map_banks)
    bank_hud = bank_spr + len(sprites) // BANK
    bank_atr = bank_hud + 2
    pl = equates(level.parent / "player.inc")
    kx = -(-0x10000 * (COLS * 16 - 256 - pl["CAM_XMAX"]) // pl["CAM_XMAX"])
    ky = -(-0x10000 * (rows * 16 - VIEW_LINES - pl["LVL_YMAX"]) // pl["LVL_YMAX"])
    (gen / "banks.inc").write_text(
        f"; generated by tools/mkrom.py\n" + "".join(f"BANK_{n}: equ {2 + i}\n" for i, n in enumerate(LOGIC))
        + f"BANK_TILES: equ {bank_tiles}\nBANK_MAP: equ {bank_map}\n"
        f"MAP_ROWS: equ {rows}\nMAP_COLS: equ {COLS}\nSPR_BASE_BANK: equ {bank_spr}\n"
        f"HUD_BANK: equ {bank_hud}\nATR_BANK: equ {bank_atr}\nATR_PACKED: equ {len(atr) - 16}\n"
        f"HUD_IMG_BANK: equ {bank_atr + 1}\nLEVEL_BANK: equ {bank_atr + 2}\nOTILE: equ 0x8000\nATR2: equ 0x8400\n"
        f"BOBHASH: equ 0x8540\n"
        f"VIEW_KX: equ {kx}\nVIEW_KY: equ {ky}\n")
    (gen / "input.inc").write_text(input_inc(script))
    (gen / "options.inc").write_text("; generated by tools/mkrom.py: build options\n" + "".join(
        f"{k}: equ {v}{' ' * max(1, 12 - len(str(v)))}; {OPTIONS[k][1]}\n" for k, v in opts.items())
        + f"INPUT_SCRIPT: equ {1 if script else 0}           ; 1: the JOY script plays (input.inc)\n")
    atr_rows = "".join(f"        dw {'ATR_RAM0' if r < 48 else 'ATR_RAM1'} + {(r if r < 48 else r - 48) * 80}\n"
                       for r in range(rows))
    (gen / "rowtab.inc").write_text("; generated by tools/mkrom.py: bank, address in the A000h window\n" + "".join(rowtab)
                                    + "atr_rows:                   ; each row of the packed attributes (page-0 RAM)\n"
                                    + atr_rows)

    code = out.parent / "code.bin"
    cmd = ["z80asm", "-I", str(gen), "-I", str(ROOT / "msx"), "-L", "-o", str(code), str(ROOT / "msx" / "rc2.asm")]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=out.parent)
    labels = r.stderr
    if r.returncode != 0:
        print(r.stderr, file=sys.stderr)
        return 1
    (out.parent / "rc2.labels").write_text(labels)
    cb = code.read_bytes()
    if len(cb) != (2 + len(LOGIC)) * BANK:
        print(f"error: code is {len(cb)} bytes (expected {(2 + len(LOGIC)) * BANK})", file=sys.stderr)
        return 1
    rom = (cb + tiles + b"".join(map_banks) + sprites + hudrt + b"\xff" * (2 * BANK - len(hudrt))
           + atr + bytes(BANK - len(atr)) + hud_img + b"\xff" * (BANK - len(hud_img))
           + otile + b"\xff" * (BANK - len(otile)))
    size = 1
    while size < len(rom):
        size *= 2
    rom += b"\xff" * (size - len(rom))
    out.write_bytes(rom)
    print(f"{out}: {len(rom) // 1024} KiB ({len(rom) // BANK} banks); tiles in {bank_tiles}-{bank_map - 1}, "
          f"map in {bank_map}-{bank_spr - 1} ({rows} rows), RoboCop sprites in {bank_spr}-"
          f"{bank_hud - 1}, HUD data in {bank_hud}-{bank_hud + 1}, attributes in {bank_atr}, HUD image in "
          f"{bank_atr + 1}, level tables in {bank_atr + 2}" + (f"; joystick script {script}" if script else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
