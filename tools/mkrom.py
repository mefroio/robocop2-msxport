#!/usr/bin/env python3
"""Builds the prototype MegaROM (Konami SCC style mapper, MegaRAM compatible).

8 KiB banks:
  0-1   code (msx/rc2.asm, org 4000h, padded up to 8000h)
  2-3   game logic modules (msx/rc2.asm org 8000h: objects.asm, mapobj.asm; one at a time at 8000h
        during the game's tick)
  4     game logic of the level (org A000h: mapped at A000h during the tick)
  5-12  level tiles: VRAM 10000h-1FFFFh (pages 2-3) generated by tools/msxconv.py
  10..  map: 25 rows of 320 bytes per bank (no row crosses a bank boundary)
  then  RoboCop sprite data (tools/msxsprites.py), from bank SPR_BASE_BANK
  then  run-time HUD data (tools/msxhudrt.py, 2 banks), from bank HUD_BANK
  then  the map attributes (tools/msxconv.py .atrp: packed, copied to page-0 RAM), bank ATR_BANK
  then  the static HUD image (tools/msxhud.py), bank HUD_IMG_BANK
  then  the level's tables, bank LEVEL_BANK: tile per DATAL tile offset (.otile, OTILE = 8000h)
  then  the play-field BOBs' atlas (tools/msxsprites.py _field.bin), bank FIELD_IMG_BANK, and
        their dynamic frames (_fdyn.bin), from bank FIELD_DYN_BANK
  then  the SCREEN 8 pictures (PICTURES)
  then  RoboCop's speech as PSG PCM (tools/msxvoice.py voice.bin) from bank VOICE_BANK, the
        speech in the music (voice_mix.bin) from VOICE_MIX_BANK, the title music for the SCC
        (tools/msxscc.py scc.bin) from bank SCC_BANK and for the OPLL (tools/msxfm.py fm.bin) from
        bank FM_BANK, the sound effects for the SCC (tools/msxsccfx.py sccfx.bin) from bank
        SCCFX_BANK (msx/music.asm reads them through the 8000h window); up to 128 banks in all
        (1 MiB, the user's choice for the speech and the next levels: a 1 MiB MegaRAM or flash
        cartridge), the ROM padded to a power of two; the banks the 8000h window maps must not be
        63 or 127 (those select the SCC's registers at 9800h, KonamiSCC: checked here)
Generates build/msx/gen/banks.inc, rowtab.inc, options.inc (build options, see OPTIONS),
input.inc (the JOY script), music.inc (the music streams' banks and addresses from the blobs'
headers, the SCC's waveforms, the OPLL's patch, the voices' state after the speech), grade.inc
(the fade's limits through the colour grade, tools/msxbright.py) and the
original's tables the logic banks include (tools/amitab.py
with analysis/amiga_tables.tsv, from the level's RAM image build/ram/level1_full.bin), copies the level palette and the HUD's
(both through the colour grade: level1_grade.pal, hud_grade.pal), the HUD (tools/msxhud.py) and RoboCop's
logic tables (tools/player.py --inc) into build/msx/gen, assembles with z80asm and writes
build/msx/rc2.rom.

The view: the MSX shows 256 x 163 of the game's 288 x 176 camera; banks.inc gets the factors of
msx/player.asm's mapping (VIEW_KX, VIEW_KY: the extra MSX camera range over the game's, 16.16).

usage: mkrom.py build/msx/level1 build/msx/rc2.rom [NAME=VALUE ...] [JOY=F:C:KEYS,...] [TELE=F:X:Y,...]
       (e.g. DEMO_ACTORS=2 for a test ROM with two demo enemies; JOY=70:40:r,120:5:ru plays
       the joystick script of tools/amigaemu.py game --joy instead of reading the controls:
       keys u d l r f pressed for C game frames from game frame F)
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from msxbright import BRIGHT, grade_pal  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
BANK = 0x2000
LOGIC = ("LC1", "LC2", "L1", "LC3", "INPUT", "FRONT", "FIELD", "MUSIC")  # logic banks after the two code banks (msx/rc2.asm
                                    # sections): modules at 8000h (one at a time), the level at A000h
PICTURES = (("title", "title_credit"), ("gameover", "gameover_text"))   # the SCREEN 8 pictures next to
                                    # the level's files (name, file): TPIC with the port's credit
                                    # (tools/msxtext.py), PIC9 with GAME OVER below it
ROWS_PER_BANK = 25
FIELD_ID0 = 0xC8                    # the play-field BOB frames' BOBHASH ids (tools/msxsprites.py)
COLS = 160
VIEW_LINES = 163                    # msx/msx.inc
OPTIONS = {
    "FORCE_V9938": (0, "1 = use the MSX2 scroll engine even on a V9958 (test)"),
    "DEMO_ACTORS": (0, "demo: objects besides RoboCop (0-5, msx/sprites.asm demo_actors)"),
    "DEMO_HUD": (0, "1 = the HUD demo drives the panel instead of the game's values"),
    "GOD": (0, "1 = test builds with a JOY script: energy and lives kept full, the level never ends"),
    "EXTJOY": (0, "1 = test build driven from openMSX (tools/openmsx_rc2.tcl rc2_drive_trace): input in ext_joy"),
    "LOCKSTEP": (0, "K > 0 = test build: two game ticks every K frames whatever the CPU time (exact display tests)"),
    "TICK_HZ": (25, "game ticks per second: 25 (the PAL original, the default) or 30 (the NTSC release)"),
    "CAD_MAX": (2, "most game ticks run for one picture: more are lost (the game slows down, as the original does when busy;"
                   " 2: an animation never skips a step of 2 ticks, about 5 % slower in busy scenes)"),
    "CAD_HOLD": (2, "the same while the V9938 scroll keeps the camera at a page's edge (its next page not built yet)"),
    "ENEMY_CAP": (1, "N > 0 = at most N enemy slots in use (the original has 5; the user chose 1): 0 = the original, for trace tests"),
    "NO_SCC": (0, "1 = the title music and the sound effects ignore an SCC (test: the OPLL or PSG modes on a KonamiSCC cartridge)"),
    "NO_FM": (0, "1 = the title music ignores an OPLL (test)"),
    "NO_SCC_INT": (0, "1 = the title music and the sound effects ignore the cartridge's own SCC: only another slot's (test: KonamiSCC + -ext scc+)"),
    "FORCE_SCC": (0, "1 = test build: the title music and the sound effects on the cartridge's SCC without testing for it"
                     " (hardware whose SCC the detection misses)"),
    "DAMAGE_X": (3, "1-3: the enemies' damage to RoboCop multiplied (their bullets, touching them): 3 = the user's choice"
                    " for the fewer enemies (ENEMY_CAP), 1 = the original, for trace tests; the missile (enemy bullet"
                    " types 1 and 2, damage 40h) at most 2, the user's choice (msx/hits.asm)"),
}
KEY_BITS = {"u": 0x01, "d": 0x02, "l": 0x04, "r": 0x08, "f": 0x10}   # the joystick byte ($802E)


def input_inc(script: str, tele: str = "") -> str:
    """input.inc (bank BANK_INPUT at A000h, msx/player.asm script_bits / script_tick): the JOY
    script as runs [frames (dw), joystick bits (db)] of the bits per game frame (every entry
    that covers a frame ORed), 0 after the last; the TELE teleports as [game frame, x, y]."""
    items = []
    for item in filter(None, script.split(",")):
        start, count, keys = item.split(":")
        bits = 0
        for k in keys:
            bits |= KEY_BITS[k]
        items.append((int(start), int(count), bits))
    end = max((f + c for f, c, _ in items), default=0)
    frames = [0] * end
    for f, c, bits in items:
        for n in range(f, f + c):
            frames[n] |= bits
    runs = []
    for b in frames:
        if runs and runs[-1][1] == b and runs[-1][0] < 0xFFFF:
            runs[-1][0] += 1
        else:
            runs.append([1, b])
    lines = ["; generated by tools/mkrom.py: joystick script (JOY=..., TELE=...; INPUT_SCRIPT in options.inc)",
             "input_script:"]
    lines += [f"        dw {n}\n        db 0x{b:02X}" for n, b in runs]
    lines.append("        dw 0")
    lines.append("input_tele:")
    for item in filter(None, tele.split(",")):
        f, x, y = (int(v, 0) for v in item.split(":"))
        lines.append(f"        dw {f}, {x}, {y}")
    lines.append("        dw 0xFFFF")
    return "\n".join(lines) + "\n"


HASH_SLOTS = 512                    # BOBHASH: 512 slots of 8 bytes and the overflow ones after them
HASH_EXTRA = 16


def bob_hash(sprites_json: Path) -> bytes:
    """The level's BOB frames (tools/msxsprites.py) by the game's (A2, D4): slots of 8 bytes [A2 (3,
    low first), D4 (2), frame id, silhouette, 0] from slot h = the XOR of those 5 bytes, plus 256
    when bit 4 of A2 is set (msx/bob.asm bf_show), on into the next slots when taken (no wrap: the
    extra slots after the 512 take the overflow); an empty slot has id FFh. A play-field frame
    (id FIELD_ID0 + its index) whose hit flash shows as a sprite silhouette has that sprite frame
    in "silhouette" (FFh: none); the sprite frame itself is then not in the table."""
    data = json.loads(sprites_json.read_text())
    frames = [f for f in data.get("bobs", []) if not f.get("spark")]
    if len(data.get("bobs", [])) > FIELD_ID0:            # (the hit spark's ids too)
        raise SystemExit(f"{len(data['bobs'])} BOB frames: too many for the frame ids")
    frames = [f for f in frames if "field" not in f]
    frames += [dict(f, id=FIELD_ID0 + f["fid"]) for f in data.get("field", [])]   # (drawn into the play field)
    table = bytearray(b"\x00\x00\x00\x00\x00\xff\x00\x00" * (HASH_SLOTS + HASH_EXTRA))
    for f in frames:
        a2, d4 = f["addr"], (f["h"] << 6) | (f["w"] // 16 + 1)
        key = bytes([a2 & 0xFF, (a2 >> 8) & 0xFF, (a2 >> 16) & 0xFF, d4 & 0xFF, d4 >> 8])
        h = (key[0] ^ key[1] ^ key[2] ^ key[3] ^ key[4]) | ((key[0] >> 4) & 1) << 8
        while table[8 * h + 5] != 0xFF:
            h += 1
        if h >= HASH_SLOTS + HASH_EXTRA:
            raise SystemExit("BOBHASH: the overflow slots are full")
        table[8 * h:8 * h + 8] = key + bytes([f["id"], f.get("sil", 0xFF), 0])
    return bytes(table)


def offsets(blob: bytes, n: int) -> list[int]:
    """The n little-endian 24-bit offsets at the start of a music blob (tools/msxscc.py, msxfm.py)."""
    return [blob[3 * i] | blob[3 * i + 1] << 8 | blob[3 * i + 2] << 16 for i in range(n)]


MVK_SCC, MVK_PSG, MVK_FM, MVK_RHY = range(4)     # msx/music.asm's stream kinds


def voice_at(blob: bytes, start: int, bank: int, kind: int, tick: int, since: int) -> bytes:
    """A music.asm voice record (MV_..., 16 bytes) as mus_adv leaves it after `tick` of the stream
    at `start` of a blob from `bank` on (records of dur, ctl and the fields its bits give): the
    next record's address and bank, the ticks left, the ctl, period, aux and rhythm volumes in
    effect, the stream's start, MV_NEW for vm_music's outputs (every field; bit 7 when an OPLL
    note began after `since`) and the kind; the rhythm's keys cleared (struck when its record
    began)."""
    word, byte = (0x40, 0x80) if kind == MVK_PSG else (0x10, 0x20)
    p, t, per, aux, rv, again = start, 0, 0, 0, [0, 0, 0], False
    while True:
        d = blob[p]
        if d == 0:
            p = start
            continue
        ctl, q = blob[p + 1], p + 2
        if kind == MVK_RHY:
            if ctl & 0x20:
                rv, q = list(blob[q:q + 3]), q + 3
        else:
            if ctl & word:
                per, q = blob[q] | blob[q + 1] << 8, q + 2
            if ctl & byte:
                aux, q = blob[q], q + 1
        again |= kind == MVK_FM and bool(ctl & 0x80) and since < t <= tick
        if t + d > tick:
            break
        t, p = t + d, q
    if kind == MVK_RHY:
        ctl &= 0xE0

    def where(off: int) -> list[int]:
        a = 0x8000 + off % BANK
        return [a & 0xFF, a >> 8, bank + off // BANK]
    return bytes(where(q) + [d - (tick - t), ctl, per & 0xFF, per >> 8, aux] + where(start)
                 + [0x31 | (0x80 if again else 0)] + rv + [kind])


def voice_inc(label: str, blob: bytes, bank: int, streams: list[tuple[int, int]], tick: int, since: int) -> list[str]:
    """voice_at of a blob's streams (header index, kind) as z80asm lines after a label."""
    out = [f"{label}:"]
    for i, kind in streams:
        rec = voice_at(blob, offsets(blob, 4)[i], bank, kind, tick, since)
        out.append("        db " + ", ".join(str(v) for v in rec))
    return out


def music_inc(scc: bytes, scc_bank: int, waves_n: int, fm: bytes, fm_bank: int, tick: int, since: int,
              sccfx: bytes) -> str:
    """music.inc (BANK_MUSIC, msx/music.asm): each stream's bank and address in the 8000h window
    (the blobs start at their banks), the SCC's waveforms, the OPLL's patch block, and the
    voices' records at `tick`, the first after the speech (vm_music: mus_snap_...)."""
    def entries(label: str, blob: bytes, bank: int, what: str) -> list[str]:
        out = [f"{label}:{' ' * max(1, 28 - len(label))}; {what}: bank, address (8000h window)"]
        for off in offsets(blob, 4):
            out.append(f"        db {bank + off // BANK}\n        dw 0x{0x8000 + off % BANK:04X}")
        return out
    def db(data: bytes) -> list[str]:
        return ["        db " + ", ".join(str(b) for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    so, fo = offsets(scc, 5), offsets(fm, 5)
    waves = scc[so[4]:so[4] + 32 * waves_n]
    lines = ["; generated by tools/mkrom.py: the title music's streams (tools/msxscc.py, tools/msxfm.py)"]
    lines += entries("mus_scc", scc, scc_bank, "the SCC's three voices, then the drums on PSG voice C")
    lines += entries("mus_fm", fm, fm_bank, "the OPLL's three voices, then its rhythm")
    lines.append("fm_patch:                           ; the custom instrument (00h-07h), the rhythm's pitches"
                 " (16h-18h, 26h-28h)")
    lines += db(fm[fo[4]:fo[4] + 14])
    lines.append(f"scc_waves:                          ; {len(waves) // 32} waveforms of 32 bytes")
    lines += db(waves)
    fwo, fwn = offsets(sccfx, 1)[0], sccfx[3]
    lines.append(f"fx_waves:                           ; the sound effects' {fwn} waveforms (tools/msxsccfx.py)")
    lines += db(sccfx[fwo:fwo + 32 * fwn])
    lines.append(f"; the voices as mus_adv leaves them after tick {tick} (the first after the speech: vm_music)")
    lines += voice_inc("mus_snap_scc", scc, scc_bank, [(0, MVK_SCC), (1, MVK_SCC), (2, MVK_SCC)], tick, since)
    lines += voice_inc("mus_snap_psg", scc, scc_bank, [(3, MVK_PSG)], tick, since)
    lines += voice_inc("mus_snap_fm", fm, fm_bank, [(0, MVK_FM), (1, MVK_FM), (2, MVK_FM)], tick, since)
    lines += voice_inc("mus_snap_rhy", fm, fm_bank, [(3, MVK_RHY)], tick, since)
    return "\n".join(lines) + "\n"


def equates(path: Path) -> dict[str, int]:
    out = {}
    for line in path.read_text().splitlines():
        if ": equ " in line:
            k, v = line.split(": equ ")
            out[k.strip()] = int(v.split()[0], 0)
    return out


def main(argv: list[str]) -> int:
    if len(argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    level, out = Path(argv[1]).resolve(), Path(argv[2]).resolve()
    opts = {k: v for k, (v, _) in OPTIONS.items()}
    script = tele = ""
    for a in argv[3:]:
        k, _, v = a.partition("=")
        if k == "JOY":
            script = v
            continue
        if k == "TELE":
            tele = v
            continue
        if k not in OPTIONS or not v:
            print(f"unknown option {a!r}; known: {', '.join(OPTIONS)}, JOY", file=sys.stderr)
            return 2
        opts[k] = int(v, 0)
    if not 1 <= opts["DAMAGE_X"] <= 3:
        print("DAMAGE_X must be 1, 2 or 3 (msx/hits.asm)", file=sys.stderr)
        return 2
    vram = level.with_suffix(".vram").read_bytes()
    mp = level.with_suffix(".map").read_bytes()
    rows = len(mp) // (COLS * 2)
    gen = out.parent / "gen"
    gen.mkdir(parents=True, exist_ok=True)
    # (names of their own: z80asm looks in its working directory, the conversions' one, first)
    (gen / "level1_grade.pal").write_bytes(grade_pal(level.with_suffix(".pal").read_bytes()))
    (gen / "hud_grade.pal").write_bytes(grade_pal((level.parent / "hud.pal").read_bytes()))
    (gen / "grade.inc").write_text("; generated by tools/mkrom.py: the colour grade (tools/msxbright.py)\n"
                                   "fade_cap:                           ; per fade step its limit (msx/logic.asm pal_fade)\n"
                                   "        db " + ", ".join(map(str, BRIGHT)) + "\n")
    for name in ("robocop.inc", "robocop_flash.inc", "robocop_field.inc", "hud_rt.inc", "player.inc",
                 "sound.inc", "text.inc", "voice.inc"):
        shutil.copy(level.parent / name, gen / name)
    atr = level.with_suffix(".atrp").read_bytes()               # (packed: copied to page-0 RAM)
    otile = level.with_suffix(".otile").read_bytes()
    otile += level.with_suffix(".atr2").read_bytes()        # (ATR2 = OTILE + 400h)
    otile += b"\xff" * (0x600 - len(otile)) + bob_hash(level.parent / "robocop.json")   # (BOBHASH = 8600h)
    hud_img = (level.parent / "hud.sc5").read_bytes()
    field_img = (level.parent / "robocop_field.bin").read_bytes()    # (the play-field BOBs' atlas)
    field_dyn = (level.parent / "robocop_fdyn.bin").read_bytes()     # (their dynamic frames: banks of their own)
    dyn_banks = max(1, -(-len(field_dyn) // BANK))
    if len(atr) > BANK or len(hud_img) > BANK:
        print("error: the map attributes or the HUD image do not fit a bank", file=sys.stderr)
        return 1
    sprites = (level.parent / "robocop.bin").read_bytes()
    hudrt = (level.parent / "hud_rt.bin").read_bytes()
    if len(hudrt) > 2 * BANK:
        print("error: hud_rt.bin is larger than two banks", file=sys.stderr)
        return 1

    r = subprocess.run([sys.executable, "-I", str(ROOT / "tools" / "amitab.py"),
                        str(ROOT / "build" / "ram" / "level1_full.bin"), str(ROOT / "analysis" / "amiga_tables.tsv"),
                        str(gen)], capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout + r.stderr, file=sys.stderr)
        return 1
    bank_tiles = 2 + len(LOGIC)
    tiles = vram[0x10000:0x20000]
    bank_map = bank_tiles + len(tiles) // BANK
    map_banks = []
    rowtab = []
    for b in range(0, rows, ROWS_PER_BANK):
        chunk = mp[b * COLS * 2:(b + ROWS_PER_BANK) * COLS * 2]
        map_banks.append(chunk + b"\xff" * (BANK - len(chunk)))
    for r in range(rows):
        rowtab.append(f"        db {bank_map + r // ROWS_PER_BANK}\n        dw 0x{0xA000 + (r % ROWS_PER_BANK) * COLS * 2:04X}\n")
    bank_spr = bank_map + len(map_banks)
    bank_hud = bank_spr + len(sprites) // BANK
    bank_atr = bank_hud + 2
    # the SCREEN 8 pictures (tools/msxpic.py: 256 bytes per line), each from a bank of its own
    pics = [(level.parent / f"{f}.sc8").read_bytes() for n, f in PICTURES]
    pic_first = []
    b = bank_atr + 4 + dyn_banks        # (bank_atr + 3: the play-field BOB atlas, then its dynamic frames)
    for p in pics:
        pic_first.append(b)
        b += -(-len(p) // BANK)
    voice = (level.parent / "voice.bin").read_bytes()   # RoboCop's speech, PSG PCM (tools/msxvoice.py),
    voice_mix = (level.parent / "voice_mix.bin").read_bytes()   # and the speech in the music
    bank_voice = b
    bank_mix = bank_voice + len(voice) // BANK
    voice += voice_mix
    scc = (level.parent / "scc.bin").read_bytes()       # the title music on the SCC (tools/msxscc.py)
    fm = (level.parent / "fm.bin").read_bytes()         #   and on the OPLL (tools/msxfm.py)
    sccfx = (level.parent / "sccfx.bin").read_bytes()   # the sound effects on the SCC (tools/msxsccfx.py)
    if offsets(sccfx, 1)[0] > BANK:                     # (msx/music.asm fx_tick maps SCCFX_BANK alone)
        print("error: the sound effects' streams take more than a bank", file=sys.stderr)
        return 1
    scc = scc + b"\xff" * (-len(scc) % BANK)
    fm = fm + b"\xff" * (-len(fm) % BANK)
    sccfx = sccfx + b"\xff" * (-len(sccfx) % BANK)
    bank_scc = bank_voice + len(voice) // BANK
    bank_fm = bank_scc + len(scc) // BANK
    bank_sccfx = bank_fm + len(fm) // BANK
    # the banks the 8000h window maps (KonamiSCC: 63 and 127 select the SCC's registers instead)
    at_8000 = list(range(2, 2 + len(LOGIC))) + list(range(2 + len(LOGIC), bank_atr + 4 + dyn_banks)) \
        + list(range(bank_voice, bank_sccfx + len(sccfx) // BANK))
    bad = sorted(set(at_8000) & {63, 127})
    if bad:
        print(f"error: bank(s) {bad} would be mapped at 8000h (the SCC's registers)", file=sys.stderr)
        return 1
    pl = equates(level.parent / "player.inc")
    kx = -(-0x10000 * (COLS * 16 - 256 - pl["CAM_XMAX"]) // pl["CAM_XMAX"])
    ky = -(-0x10000 * (rows * 16 - VIEW_LINES - pl["LVL_YMAX"]) // pl["LVL_YMAX"])
    (gen / "banks.inc").write_text(
        f"; generated by tools/mkrom.py\n" + "".join(f"BANK_{n}: equ {2 + i}\n" for i, n in enumerate(LOGIC))
        + f"BANK_TILES: equ {bank_tiles}\nBANK_MAP: equ {bank_map}\n"
        f"MAP_ROWS: equ {rows}\nMAP_COLS: equ {COLS}\nSPR_BASE_BANK: equ {bank_spr}\n"
        f"HUD_BANK: equ {bank_hud}\nATR_BANK: equ {bank_atr}\nATR_PACKED: equ {len(atr) - 16}\n"
        f"HUD_IMG_BANK: equ {bank_atr + 1}\nLEVEL_BANK: equ {bank_atr + 2}\nFIELD_IMG_BANK: equ {bank_atr + 3}\n"
        f"FIELD_DYN_BANK: equ {bank_atr + 4}\n"
        f"OTILE: equ 0x8000\nATR2: equ 0x8400\n"
        f"BOBHASH: equ 0x8600\n"
        + "".join(f"PIC_{n.upper()}_BANK: equ {pic_first[i]}\nPIC_{n.upper()}_LINES: equ {len(pics[i]) // 256}\n"
                  for i, (n, f) in enumerate(PICTURES)) +
        f"VOICE_BANK: equ {bank_voice}\nVOICE_MIX_BANK: equ {bank_mix}\nSCC_BANK: equ {bank_scc}\nFM_BANK: equ {bank_fm}\n"
        f"SCCFX_BANK: equ {bank_sccfx}\n"
        f"VIEW_KX: equ {kx}\nVIEW_KY: equ {ky}\n")
    (gen / "input.inc").write_text(input_inc(script, tele))
    vq = equates(level.parent / "voice.inc")
    (gen / "music.inc").write_text(music_inc(scc, bank_scc, equates(level.parent / "scc.inc")["SCC_WAVES"], fm, bank_fm,
                                             vq["VOICE_TICK"] + vq["VOICE_TICKS"], vq["VOICE_TICK"], sccfx))
    (gen / "options.inc").write_text("; generated by tools/mkrom.py: build options\n" + "".join(
        f"{k}: equ {v}{' ' * max(1, 12 - len(str(v)))}; {OPTIONS[k][1]}\n" for k, v in opts.items())
        + f"INPUT_SCRIPT: equ {1 if script or opts['EXTJOY'] else 0}           ; 1: the JOY script plays (input.inc)\n")
    atr_rows = "".join(f"        dw {'ATR_RAM0' if r < 48 else 'ATR_RAM1'} + {(r if r < 48 else r - 48) * 80}\n"
                       for r in range(rows))
    def db_rows(label: str, values: list[int]) -> str:
        return f"{label}:\n" + "".join("        db " + ", ".join(map(str, values[i:i + 16])) + "\n"
                                        for i in range(0, len(values), 16))
    # the view's offset over the camera per 16 pixels of camera (msx/player.asm pl_view)
    view_x = [((16 * i + 8) * kx) >> 16 for i in range(pl["CAM_XMAX"] // 16 + 3)]
    view_y = [((16 * i + 8) * ky) >> 16 for i in range(pl["LVL_YMAX"] // 16 + 3)]
    (gen / "rowtab.inc").write_text("; generated by tools/mkrom.py: bank, address in the A000h window\n" + "".join(rowtab)
                                    + "atr_rows:                   ; each row of the packed attributes (page-0 RAM)\n"
                                    + atr_rows + db_rows("view_offx", view_x) + db_rows("view_offy", view_y))

    code = out.parent / "code.bin"
    cmd = ["z80asm", "-I", str(gen), "-I", str(ROOT / "msx"), "-L", "-o", str(code), str(ROOT / "msx" / "rc2.asm")]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=out.parent)
    labels = r.stderr
    if r.returncode != 0:
        print(r.stderr, file=sys.stderr)
        return 1
    out.with_suffix(".labels").write_text(labels)       # (rc2.rom: rc2.labels, rc2_ext.rom: rc2_ext.labels)
    cb = code.read_bytes()
    if len(cb) != (2 + len(LOGIC)) * BANK:
        print(f"error: code is {len(cb)} bytes (expected {(2 + len(LOGIC)) * BANK})", file=sys.stderr)
        return 1
    rom = (cb + tiles + b"".join(map_banks) + sprites + hudrt + b"\xff" * (2 * BANK - len(hudrt))
           + atr + bytes(BANK - len(atr)) + hud_img + b"\xff" * (BANK - len(hud_img))
           + otile + b"\xff" * (BANK - len(otile))
           + field_img + b"\xff" * (BANK - len(field_img))
           + field_dyn + b"\xff" * (dyn_banks * BANK - len(field_dyn))
           + b"".join(p + b"\xff" * (-len(p) % BANK) for p in pics)
           + voice + scc + fm + sccfx)
    if len(rom) > 0x100000:
        print(f"error: the ROM takes {len(rom) // BANK} banks (1 MiB: 128)", file=sys.stderr)
        return 1
    size = 1
    while size < len(rom):
        size *= 2
    rom += b"\xff" * (size - len(rom))
    # (msx/sound.asm scc_pat takes one value read back from 9800h of the cartridge's own slot
    # for an SCC: on a MegaRAM or a Konami mapper holding this image each value written there
    # selects that bank at 8000h, the byte read back being the bank's at 1800h; on a Konami SCC
    # mapper without the chip it is bank 3Fh's: none may be a test value)
    nb = len(rom) // BANK
    tests = (0x5A, 0xBF, 0x24, 0x89)
    hits = [v for v in tests if rom[(v % nb) * BANK + 0x1800] == v] + \
        [v for v in tests if rom[(0x3F % nb) * BANK + 0x1800] == v]
    if hits:
        print(f"error: the SCC test would find an SCC in a cartridge without one (value(s) "
              f"{', '.join(f'{v:02X}h' for v in hits)} at a bank's 1800h)", file=sys.stderr)
        return 1
    out.write_bytes(rom)
    print(f"{out}: {len(rom) // 1024} KiB ({len(rom) // BANK} banks); tiles in {bank_tiles}-{bank_map - 1}, "
          f"map in {bank_map}-{bank_spr - 1} ({rows} rows), RoboCop sprites in {bank_spr}-"
          f"{bank_hud - 1}, HUD data in {bank_hud}-{bank_hud + 1}, attributes in {bank_atr}, HUD image in "
          f"{bank_atr + 1}, level tables in {bank_atr + 2}" + (f"; joystick script {script}" if script else ""))
    return 0


