#!/usr/bin/env python3
"""Robocop 2 sprite (BOB) catalogue from the Ghidra assembly exported through REA.

Input: build/rea/asm/<address>.json (generated by tools/rea_dump_asm.sh with the REA CLI).
For every call to draw_bob ($AB08) or its wrappers, follows the values of A2 (lea +
adda/suba + indexed table) and D4 (BLTSIZE) linearly and enumerates the frames.
The level of each reference comes from the code (spawn lists, special objects, resident
PERMA/SPERMA); only references without such evidence fall back to the mask score (real
masks have long continuous runs; non-sprite data toggles bit by bit).

usage:
  bobcatalog.py catalog            -> build/sprites/catalog.json
  bobcatalog.py sheets             -> build/sprites/<level>_<routine>.png
"""
from __future__ import annotations

import json
import re
import struct
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from amigahw import rgb12_to_rgb24  # noqa: E402
from planar import write_png  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
ASM = ROOT / "build" / "rea" / "asm"
OUT = ROOT / "build" / "sprites"
DRAW = 0xAB08
LEVELS = {"level1": ("build/ram/level1_full.bin", 0xFFF6), "level2": ("build/ram/level2_full.bin", 0x10036),
          "level3": ("build/ram/level3_full.bin", 0x10036)}
INS = re.compile(r"^0x([0-9a-f]+): (\S+)\s*(.*)$")
PERMA = (0x58850, 0x6FFA0)
SPERMA = (0x4B68A, 0x5884E)
# special objects (list patched into $8B54, dispatch $8B92): routine -> levels (via REA, per-level records)
SPECIAL_LEVELS = {0x8DE6: {"level1", "level2", "level3"}, 0x8F02: {"level2"}, 0x8B9E: {"level1"}}
# enemy types of the per-level spawn lists $9626/$97B0/$99E2 (type at +4; verified via REA)
LEVEL_ENEMY_TYPES = {"level1": {4, 12, 23, 25, 26, 28, 32, 44, 45},
                     "level2": {1, 2, 4, 5, 6, 12, 13, 14, 45, 49},
                     "level3": {21, 22, 33, 35, 36, 38, 39, 40, 41, 42, 43, 47, 48, 50, 52}}
OBJ_DESC = 0xBEB0


def proc_levels(main: bytes) -> dict[int, set[str]]:
    """Routine -> levels, from the code: spawn lists (type -> level) and descriptors (type -> routine)."""
    out: dict[int, set[str]] = {a: set(v) for a, v in SPECIAL_LEVELS.items()}
    for t in range(1, 53):
        d = OBJ_DESC + 16 * t
        h = d + struct.unpack_from(">h", main, d - 0x8000)[0]
        lvls = {lv for lv, types in LEVEL_ENEMY_TYPES.items() if t in types}
        if lvls:
            out.setdefault(h, set()).update(lvls)
    return out


def load_procs() -> dict[int, tuple[str, list[tuple[int, str, str]]]]:
    procs = {}
    for f in sorted(ASM.glob("*.json")):
        nr = json.loads(f.read_text())["normalized_result"]
        lines = []
        for t in nr["instructions"]:
            m = INS.match(t)
            if m:
                lines.append((int(m.group(1), 16), m.group(2), m.group(3)))
        procs[int(nr["procedure"]["address"], 16)] = (nr["procedure"]["name"], lines)
    return procs


def call_target(mn: str, ops: str) -> int | None:
    if mn.split(".")[0] in ("bsr", "bra", "jsr", "jmp"):
        m = re.fullmatch(r"0x([0-9a-f]+)", ops.strip())
        if m:
            return int(m.group(1), 16)
    return None


def draw_targets(procs) -> set[int]:
    """draw_bob and short wrappers that end up calling draw_bob."""
    targets = {DRAW}
    changed = True
    while changed:
        changed = False
        for a, (_n, lines) in procs.items():
            if a in targets or len(lines) > 14:
                continue
            if any(call_target(mn, ops) in targets for _x, mn, ops in lines):
                targets.add(a)
                changed = True
    return targets


def scan(procs, targets):
    refs = []
    for pa, (name, lines) in procs.items():
        if pa in targets:
            continue
        a2 = d4 = table = None
        adj: list[int] = []
        for addr, mn, ops in lines:
            m = re.fullmatch(r"\(0x([0-9a-f]+)\)\.l, A2", ops) if mn.startswith("lea") else None
            if m:
                a2, adj, table = int(m.group(1), 16), [], None
                continue
            m = re.fullmatch(r"#0x([0-9a-f]+), A2", ops) if mn in ("adda.w", "suba.w", "adda.l", "suba.l") else None
            if m and a2 is not None:
                adj.append(int(m.group(1), 16) * (-1 if mn.startswith("suba") else 1))
                continue
            m = re.match(r"\(0x([0-9a-f]+),PC,D\dw", ops) if mn == "adda.w" else None
            if m and ops.endswith("A2"):
                table = int(m.group(1), 16)
                continue
            m = re.fullmatch(r"#0x([0-9a-f]+), D4w", ops) if mn == "move.w" else None
            if m:
                d4 = int(m.group(1), 16)
                continue
            t = call_target(mn, ops)
            if t in targets and a2 is not None and d4 is not None and 1 < (d4 & 63) <= 9 and (d4 >> 6) >= 4:
                refs.append({"proc": pa, "proc_name": name, "site": addr, "base": a2, "adjust": list(adj),
                             "table": table, "bltsize": d4})
    return refs


def frames_for(ref, main: bytes) -> list[int]:
    wb, h = ((ref["bltsize"] & 63) - 1) * 2, ref["bltsize"] >> 6
    fs = 5 * wb * h
    addrs = {ref["base"]}
    for a in ref["adjust"]:
        addrs |= {x + a for x in addrs}
    if ref["table"] is not None:
        offs = []
        t = ref["table"]
        for i in range(32):
            if not 0x8000 <= t + 2 * i < 0x8000 + len(main) - 1:
                break
            v = struct.unpack_from(">h", main, t + 2 * i - 0x8000)[0]
            if v < 0 or v % fs or v > 40 * fs or (offs and v in offs):
                break
            offs.append(v)
        addrs = {x + o for x in addrs for o in offs} or addrs
    return sorted(addrs)


def mask_score(ram: bytes, addr: int, wb: int, h: int) -> float:
    """0..1: fraction of mask pixels without a transition to the neighbour; plus a sane density."""
    if addr < 0 or addr + 5 * wb * h > len(ram):
        return 0.0
    m = ram[addr:addr + wb * h]
    ones = sum(bin(b).count("1") for b in m)
    dens = ones / (wb * h * 8)
    if not 0.04 <= dens <= 0.97:
        return 0.0
    trans = 0
    for y in range(h):
        bits = int.from_bytes(m[y * wb:(y + 1) * wb], "big")
        trans += bin((bits ^ (bits >> 1)) & ((1 << (wb * 8 - 1)) - 1)).count("1")
    return 1 - trans / (h * (wb * 8 - 1))


def cmd_catalog() -> int:
    procs = load_procs()
    targets = draw_targets(procs)
    main = (ROOT / "build/extracted/boot/main_8000.bin").read_bytes()
    rams = {k: (ROOT / v[0]).read_bytes() for k, v in LEVELS.items()}
    refs = scan(procs, targets)
    plv = proc_levels(main)
    for r in refs:
        wb, h = ((r["bltsize"] & 63) - 1) * 2, r["bltsize"] >> 6
        r["width"], r["height"] = wb * 8, h
        r["frames"] = frames_for(r, main)
        score = {lv: round(sum(mask_score(ram, f, wb, h) for f in r["frames"]) / len(r["frames"]), 3)
                 for lv, ram in rams.items()}
        r["score"] = score
        levels = plv.get(r["proc"], set())
        base = r["base"]
        if PERMA[0] <= base < PERMA[1]:
            r["level"], r["evidence"] = "common", "PERMA (resident)"
        elif SPERMA[0] <= base < SPERMA[1] and levels and levels <= {"level1", "level2"}:
            r["level"], r["evidence"] = "common", "SPERMA (levels 1-2)"
        elif len(levels) == 1:
            r["level"], r["evidence"] = next(iter(levels)), "code (spawn list/special object)"
        elif levels:
            r["level"], r["evidence"] = "+".join(sorted(levels)), "code (several levels; per-level data)"
        else:
            best = max(score, key=score.get)
            r["level"] = best if score[best] >= 0.80 else None
            r["evidence"] = "inferred (mask score)"
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "catalog.json").write_text(json.dumps({"draw_targets": sorted(targets), "refs": refs}, indent=1))
    print(f"{len(procs)} routines read, draw wrappers: {[hex(t) for t in sorted(targets)]}")
    agg = defaultdict(int)
    for r in refs:
        agg[(r["level"], r["evidence"].split(" ")[0])] += 1
    print(f"{len(refs)} sprite references:")
    for (lv, ev), n in sorted(agg.items(), key=str):
        print(f"   {str(lv):24} {ev:10} {n}")
    return 0


def cmd_sheets() -> int:
    cat = json.loads((OUT / "catalog.json").read_text())
    main = (ROOT / "build/extracted/boot/main_8000.bin").read_bytes()
    groups = defaultdict(list)
    for r in cat["refs"]:
        if r["level"]:
            for lv in r["level"].split("+"):
                groups[(lv, r["proc_name"])].append(r)
    for (lv, pname), refs in sorted(groups.items()):
        src = LEVELS["level1" if lv == "common" else lv]
        ram = (ROOT / src[0]).read_bytes()
        po = src[1] - 0x8000
        pal = [(0, 0, 0)] + [rgb12_to_rgb24(struct.unpack_from(">H", main, po + 2 * i)[0]) for i in range(15)]
        tiles = []
        for r in refs:
            wb, h = r["width"] // 8, r["height"]
            for f in r["frames"]:
                tiles.append((f, wb, h))
        tiles = list(dict.fromkeys(tiles))
        cell_w = max(wb for _f, wb, _h in tiles) * 8 + 2
        cell_h = max(h for _f, _wb, h in tiles) + 2
        cols = min(10, len(tiles))
        rows = (len(tiles) + cols - 1) // cols
        S = 3
        W, H = cols * cell_w, rows * cell_h
        canvas = [[(60, 60, 60)] * W for _ in range(H)]
        for i, (f, wb, h) in enumerate(tiles):
            ox, oy = (i % cols) * cell_w + 1, (i // cols) * cell_h + 1
            ps = wb * h
            for y in range(h):
                for x in range(wb * 8):
                    byte, bit = y * wb + (x >> 3), 0x80 >> (x & 7)
                    if not ram[f + byte] & bit:
                        canvas[oy + y][ox + x] = (255, 0, 255)
                        continue
                    v = sum(1 << p for p in range(4) if ram[f + ps * (p + 1) + byte] & bit)
                    canvas[oy + y][ox + x] = pal[v]
        rows_px = [b"".join(bytes(c) * S for c in row) for row in canvas for _ in range(S)]
        path = OUT / f"{lv}_{re.sub(r'[^A-Za-z0-9_]+', '_', pname)}.png"
        write_png(path, W * S, H * S, rows_px)
        print(f"{path.name}: {len(tiles)} frames")
    return 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "catalog"
    raise SystemExit(cmd_catalog() if cmd == "catalog" else cmd_sheets())
