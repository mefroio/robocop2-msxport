#!/usr/bin/env python3
"""Tables of the original game for the MSX port's game logic, extracted at build time.

The ported routines read the original's tables (offsets per direction, animation steps, spawn
lists...) from copies the build puts into the logic code banks, so no data of the game lives in
the repository. analysis/amiga_tables.tsv lists them:

    LABEL  ADDRESS  COUNT  KIND  BANK  [comment]

KIND: b (bytes), w (words: dw, little-endian), l (longs: two little-endian words in the Amiga's
word order, the high word first, as the port's variable mirror keeps them), x (COUNT bytes of
Amiga memory as the mirror keeps it: the two bytes of every word swapped, so words are
little-endian and the byte at A is at A ^ 1; for the copies of the game's lists), s:PATTERN (records
of fields b / w, e.g. s:wwbbbbwwbb for 14-byte records; COUNT 0: up to the record whose first
word is negative, which ends the list and is copied as that one word). BANK names the
logic bank whose source includes the output (build/msx/gen/at_<BANK>.inc). ADDRESS is read from
the level's RAM image (tools/ramimage.py), which holds the main code at $8000 as the disk has it.

usage: amitab.py build/ram/level1_full.bin analysis/amiga_tables.tsv build/msx/gen
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

BANKS = ("fixed", "c1", "c2", "l1", "l2", "l3")   # fixed code, logic modules, level banks
                                                 # (msx/rc2.asm includes every at_<bank>.inc)


def parse(spec: Path) -> list[dict]:
    rows = []
    for n, line in enumerate(spec.read_text().splitlines(), 1):
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        f = s.split(None, 5)
        if len(f) < 5:
            raise SystemExit(f"{spec}:{n}: expected LABEL ADDRESS COUNT KIND BANK")
        label, addr, count, kind, bank = f[:5]
        if kind not in ("b", "w", "l", "x") and not (kind.startswith("s:") and set(kind[2:]) <= {"b", "w"}):
            raise SystemExit(f"{spec}:{n}: unknown kind {kind!r}")
        rows.append({"label": label, "addr": int(addr, 16), "count": int(count, 0), "kind": kind,
                     "bank": bank, "comment": f[5] if len(f) > 5 else ""})
    return rows


def emit(img: bytes, r: dict) -> str:
    a, n, k = r["addr"], r["count"], r["kind"]
    out = [f"{r['label']}:{' ' * max(1, 15 - len(r['label']))}; ${a:05X}, {n} x {k}"
           + (f": {r['comment']}" if r["comment"] else "") + "\n"]
    if k == "x":
        raw = bytearray(img[a:a + n + (n & 1)])
        raw[0::2], raw[1::2] = raw[1::2], raw[0::2]
        for i in range(0, len(raw), 16):
            out.append("        db " + ",".join(f"0x{v:02X}" for v in raw[i:i + 16]) + "\n")
    elif k == "b":
        vals = list(img[a:a + n])
        for i in range(0, n, 16):
            out.append("        db " + ",".join(f"0x{v:02X}" for v in vals[i:i + 16]) + "\n")
    elif k.startswith("s:"):
        pat = k[2:]
        size = sum(2 if c == "w" else 1 for c in pat)
        i = 0
        while n == 0 or i < n:
            r0 = a + i * size
            if n == 0 and img[r0] & 0x80:
                out.append(f"        dw 0x{struct.unpack_from('>H', img, r0)[0]:04X}  ; end\n")
                break
            o = r0
            for j, c in enumerate(pat):
                note = f"  ; record {i}" if j == 0 else ""
                if c == "w":
                    out.append(f"        dw 0x{struct.unpack_from('>H', img, o)[0]:04X}{note}\n")
                    o += 2
                else:
                    out.append(f"        db 0x{img[o]:02X}{note}\n")
                    o += 1
            i += 1
    elif k == "w":
        vals = [struct.unpack_from(">H", img, a + 2 * i)[0] for i in range(n)]
        for i in range(0, n, 8):
            out.append("        dw " + ",".join(f"0x{v:04X}" for v in vals[i:i + 8]) + "\n")
    else:
        vals = [struct.unpack_from(">HH", img, a + 4 * i) for i in range(n)]
        for i in range(0, n, 4):
            out.append("        dw " + ",".join(f"0x{h:04X},0x{lo:04X}" for h, lo in vals[i:i + 4]) + "\n")
    out.append(f"{r['label']}_end:\n")
    return "".join(out)


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    img = Path(sys.argv[1]).read_bytes()
    rows = parse(Path(sys.argv[2]))
    out = Path(sys.argv[3])
    out.mkdir(parents=True, exist_ok=True)
    banks: dict[str, list[str]] = {b: [] for b in BANKS}
    for r in rows:
        banks.setdefault(r["bank"], []).append(emit(img, r))
    for bank, parts in banks.items():
        (out / f"at_{bank}.inc").write_text(f"; generated by tools/amitab.py from {Path(sys.argv[1]).name}\n"
                                            + "".join(parts))
    print(f"{out}: {len(rows)} tables in {len(banks)} banks ({', '.join(sorted(banks))})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
